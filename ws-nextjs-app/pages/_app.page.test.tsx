import { lazy, Suspense, use, type PropsWithChildren } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { AppProps } from 'next/app';
import {
  act,
  render,
  screen,
} from '#app/components/react-testing-library-with-providers';
import { AccountContext } from '#app/contexts/AccountContext';
import loadQueryConsumer from '#app/contexts/QueryContext/loadQueryConsumer';
import mockIdctaConfig from '#app/contexts/AccountContext/mocks';
import mockMatchMedia from '#testHelpers/mockMatchMedia';
import EmbedHtml from '#app/components/Embeds/EmbedHtml';
import CustomApp from './_app.page';

jest.mock('#app/components/ThemeProvider', () =>
  jest.requireActual('#app/components/ThemeProvider/__mocks__'),
);

jest.mock('#app/components/PageLayoutWrapper', () => ({
  __esModule: true,
  default: ({ children }: PropsWithChildren) => children,
}));

jest.mock('#app/components/ThemeProviderSCSSModules', () => ({
  __esModule: true,
  default: ({ children }: PropsWithChildren) => children,
}));

const QueryStatus = () => {
  const queryClient = useQueryClient();
  return <p>{queryClient ? 'Query ready' : 'Query unavailable'}</p>;
};

describe('CustomApp', () => {
  beforeEach(() => {
    mockMatchMedia();
  });

  it('does not define or inherit getInitialProps', () => {
    expect(CustomApp).not.toHaveProperty('getInitialProps');
  });

  it('preserves VJ DOM while signing in, loading query code and signing out', async () => {
    const pending = Promise.withResolvers<{
      default: typeof QueryStatus;
    }>();
    const Authenticated = lazy(() =>
      loadQueryConsumer(pending.promise).then(Component => ({
        default: Component,
      })),
    );

    const Page = () => {
      const { isArticlePersonalizationEnabled } = use(AccountContext);
      return (
        <>
          <EmbedHtml embeddableContent='<div id="vj-content">VJ content</div>' />
          {isArticlePersonalizationEnabled && (
            <Suspense fallback={<p>Loading query code</p>}>
              <Authenticated />
            </Suspense>
          )}
        </>
      );
    };

    const pageProps: Parameters<typeof CustomApp>[0]['pageProps'] = {
      service: 'portuguese',
      isAmp: false,
      isNextJs: true,
      serverSideExperiments: null,
      pageData: { metadata: { type: 'article' } },
      pageType: 'article',
      pathname: '/portuguese/articles/ckq5ne65q14go',
      status: 200,
      showAdsBasedOnLocation: false,
      navItems: null,
      idctaConfig: mockIdctaConfig,
      toggles: {
        uasPersonalization: { enabled: true, value: 'portuguese' },
      },
    };
    const appProps = {
      Component: Page,
      pageProps,
      router: {} as AppProps['router'],
    };

    const { rerender } = render(<CustomApp {...appProps} />);
    const embed = await screen.findByTestId('embed');
    const vjContent = screen.getByText('VJ content');
    const generatedContent = document.createElement('p');
    generatedContent.textContent = 'Generated by VJ script';
    vjContent.appendChild(generatedContent);

    rerender(
      <CustomApp
        {...appProps}
        pageProps={{
          ...appProps.pageProps,
          idctaConfig: { ...mockIdctaConfig, initialIsSignedIn: true },
        }}
      />,
    );

    expect(screen.getByText('Loading query code')).toBeInTheDocument();
    expect(screen.getByTestId('embed')).toBe(embed);
    expect(screen.getByText('Generated by VJ script')).toBe(generatedContent);

    await act(async () => {
      pending.resolve({ default: QueryStatus });
    });

    expect(screen.getByText('Query ready')).toBeInTheDocument();
    expect(screen.getByTestId('embed')).toBe(embed);
    expect(screen.getByText('Generated by VJ script')).toBe(generatedContent);

    rerender(<CustomApp {...appProps} />);

    expect(screen.queryByText('Query ready')).not.toBeInTheDocument();
    expect(screen.getByTestId('embed')).toBe(embed);
    expect(screen.getByText('Generated by VJ script')).toBe(generatedContent);
  });
});
